var builder = WebApplication.CreateBuilder(args);

// Add services to the container.
// Learn more about configuring OpenAPI at https://aka.ms/aspnet/openapi
builder.Services.AddOpenApi();
builder.Services.AddSwaggerGen(); // cài thêm dotnet add package Swashbuckle.AspNetCore
builder.Services.AddControllers(); // Đăng ký DI controllers

var app = builder.Build();

// Configure the HTTP request pipeline.
if (app.Environment.IsDevelopment())
{
    app.MapOpenApi();
    
    // Thêm Swagger UI để hiển thị giao diện OpenAPI Documentation
    app.UseSwagger();
    app.UseSwaggerUI(); // Mở trình duyệt ở http://localhost:{PORT}/swagger/index.html
}

app.UseHttpsRedirection();

